CREATE TABLE public.resultado_academico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estudiante_id BIGINT NOT NULL,
    resultado VARCHAR(20) NOT NULL DEFAULT 'DESCONOCIDO',
    fecha_observacion DATE,
    fuente_evidencia VARCHAR(150),
    observaciones TEXT,
    verificado BOOLEAN NOT NULL DEFAULT FALSE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_en TIMESTAMPTZ,

    CONSTRAINT fk_resultado_academico_estudiante
        FOREIGN KEY (estudiante_id)
        REFERENCES public.estudiante(id),

    CONSTRAINT chk_resultado_academico_valido
        CHECK (resultado IN ('CONTINUIDAD', 'DESERCION', 'DESCONOCIDO')),

    CONSTRAINT chk_resultado_verificado
        CHECK (
            resultado = 'DESCONOCIDO'
            OR (
                verificado = TRUE
                AND fecha_observacion IS NOT NULL
                AND fuente_evidencia IS NOT NULL
                AND LENGTH(TRIM(fuente_evidencia)) > 0
            )
        )
);

CREATE INDEX idx_resultado_academico_estudiante_fecha
    ON public.resultado_academico (estudiante_id, fecha_observacion DESC);

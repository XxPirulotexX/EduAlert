
-- Esquema inicial de EduAlerta.
-- Esta migración se ejecuta en bases de datos nuevas.
-- En la base existente se registrará una línea base en la versión 1.

CREATE TABLE public.usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actualizado_en TIMESTAMP(6) WITH TIME ZONE,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(20) NOT NULL,
    CONSTRAINT uk_usuario_correo UNIQUE (correo)
);

CREATE TABLE public.estudiante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actualizado_en TIMESTAMP(6) WITH TIME ZONE,
    apellidos VARCHAR(100) NOT NULL,
    codigo_estudiantil VARCHAR(50) NOT NULL,
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    nombres VARCHAR(100) NOT NULL,
    usuario_id BIGINT,
    grado VARCHAR(10),
    promedio_actual NUMERIC(3,2),
    CONSTRAINT uk_estudiante_codigo_estudiantil
        UNIQUE (codigo_estudiantil),
    CONSTRAINT uk_estudiante_usuario UNIQUE (usuario_id),
    CONSTRAINT fk_estudiante_usuario
        FOREIGN KEY (usuario_id) REFERENCES public.usuario(id)
);

CREATE TABLE public.evaluacion_riesgo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    fuente VARCHAR(30) NOT NULL,
    nivel VARCHAR(20) NOT NULL,
    observaciones VARCHAR(500),
    version_modelo VARCHAR(80),
    estudiante_id BIGINT NOT NULL,
    CONSTRAINT fk_evaluacion_riesgo_estudiante
        FOREIGN KEY (estudiante_id) REFERENCES public.estudiante(id)
);

CREATE TABLE public.alerta_temprana (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actualizado_en TIMESTAMP(6) WITH TIME ZONE,
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    estado VARCHAR(30) NOT NULL,
    nivel_riesgo VARCHAR(20) NOT NULL,
    senal VARCHAR(500) NOT NULL,
    estudiante_id BIGINT NOT NULL,
    CONSTRAINT fk_alerta_estudiante
        FOREIGN KEY (estudiante_id) REFERENCES public.estudiante(id)
);

CREATE TABLE public.seguimiento_alerta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    creado_en TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    observaciones VARCHAR(1000) NOT NULL,
    alerta_id BIGINT NOT NULL,
    responsable_usuario_id BIGINT NOT NULL,
    CONSTRAINT fk_seguimiento_alerta
        FOREIGN KEY (alerta_id) REFERENCES public.alerta_temprana(id),
    CONSTRAINT fk_seguimiento_responsable
        FOREIGN KEY (responsable_usuario_id) REFERENCES public.usuario(id)
);
